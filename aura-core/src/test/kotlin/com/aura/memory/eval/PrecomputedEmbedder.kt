package com.aura.memory.eval

import com.aura.memory.CountingEmbedder
import com.aura.memory.Embedder
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.util.concurrent.atomic.AtomicInteger

/**
 * An [Embedder] that serves vectors computed elsewhere, keyed by exact text.
 *
 * This exists to answer one question — **how much would a real embedding model
 * actually buy this system?** — for the cost of one Python script instead of the
 * five-to-ten days an on-device ONNX runtime would take. Run the harness against
 * `local-hash-v2` and against `gte-small`, read the synonym-only class, and the
 * ONNX phase is either justified or it is not, before a line of it is written.
 *
 * The answer only means something on a corpus of REAL memories. On the synthetic
 * scaffold, a semantic model and a hash score about the same, because the
 * scaffold has no synonymy to find — see [EvalFixtures.isScaffold].
 *
 * Generated by `scripts/gen_eval_vectors.py`. Vector files are NOT committed:
 * they are derived from `corpus.jsonl`, they are megabytes of floats, and a
 * stale one silently measures the wrong model.
 */
class PrecomputedEmbedder private constructor(
    private val vectors: Map<String, FloatArray>,
    private val modelId: String,
    private val dim: Int,
    override val callCount: AtomicInteger = AtomicInteger(0),
) : Embedder, CountingEmbedder {

    override fun modelId(): String = modelId

    override fun dimension(): Int = dim

    /**
     * Look up [text]'s vector, or fail.
     *
     * Deliberately not a zero vector or a hash fallback on a miss. A missing
     * vector means the file was generated against a different corpus, and the
     * quiet handling of that is a scorecard that blames the model for a fixture
     * problem — which is the one outcome that would make this whole experiment
     * worse than not running it.
     */
    override suspend fun embed(text: String): FloatArray {
        callCount.incrementAndGet()
        return vectors[text.trim()] ?: error(
            "No precomputed vector for \"${text.take(60)}…\" in $modelId. The vector file was " +
                "generated from a different corpus or query set; regenerate it with " +
                "scripts/gen_eval_vectors.py. Falling back here would score the fixture, not the model.",
        )
    }

    @Serializable
    private data class Row(
        val text: String,
        val vector: List<Float>,
        @SerialName("model") val model: String = "",
    )

    companion object {

        private val json = Json { ignoreUnknownKeys = true; isLenient = true }

        /**
         * Load `/retrieval-eval/vectors-<modelId>.jsonl` from the test classpath,
         * or null when it is absent.
         *
         * Null rather than an error, because these files are a local experiment
         * artifact and CI has neither Python nor the real corpus. The caller must
         * then REPORT that the comparison did not run rather than pass quietly —
         * see how `RetrievalEvalTest` handles it.
         */
        fun loadOrNull(modelId: String): PrecomputedEmbedder? {
            val path = "/retrieval-eval/vectors-$modelId.jsonl"
            val text = PrecomputedEmbedder::class.java.getResourceAsStream(path)
                ?.bufferedReader()?.use { it.readText() } ?: return null
            return parse(text, modelId)
        }

        /** Available `vectors-*.jsonl` model ids, in the order given. */
        fun available(candidates: List<String>): List<String> =
            candidates.filter { PrecomputedEmbedder::class.java.getResource("/retrieval-eval/vectors-$it.jsonl") != null }

        fun parse(text: String, modelId: String): PrecomputedEmbedder {
            val rows = text.lineSequence()
                .map { it.trim() }
                .filter { it.isNotEmpty() && !it.startsWith("//") }
                .map { json.decodeFromString<Row>(it) }
                .toList()
            require(rows.isNotEmpty()) { "vectors-$modelId.jsonl is empty" }

            val dims = rows.map { it.vector.size }.distinct()
            require(dims.size == 1) {
                "vectors-$modelId.jsonl mixes dimensions $dims — two models' output ended up in one file"
            }

            // Normalize on load rather than trusting the generator. MemoryStore's
            // similarity is a bare dot product on the assumption that both sides
            // are unit vectors, so an unnormalized file would not fail, it would
            // just rank by magnitude and quietly produce a plausible wrong answer.
            val byText = rows.associate { it.text.trim() to normalize(it.vector.toFloatArray()) }
            require(byText.size == rows.size) {
                "vectors-$modelId.jsonl has ${rows.size - byText.size} duplicate text keys"
            }
            return PrecomputedEmbedder(byText, modelId, dims.single())
        }

        private fun normalize(v: FloatArray): FloatArray {
            var sum = 0.0
            for (x in v) sum += x.toDouble() * x
            val len = kotlin.math.sqrt(sum).toFloat()
            if (len <= 0f) return v
            for (i in v.indices) v[i] /= len
            return v
        }

        /**
         * The models the Gate B experiment compares, cheapest first.
         *
         * `local-hash-v2` is the floor — what every user without an Ollama key
         * gets today. `gte-small` is what the ONNX phase would ship.
         * `nomic-embed-text` is what the existing cloud path already buys, and is
         * the ceiling: on-device is not going to beat it, so a small gap between
         * rows two and three means the whole ONNX phase is buying very little.
         */
        val GATE_B_MODELS = listOf("gte-small", "bge-small-en-v1.5", "nomic-embed-text")
    }
}
