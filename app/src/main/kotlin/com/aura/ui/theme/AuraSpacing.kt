package com.aura.ui.theme

import androidx.compose.ui.unit.dp

/** Aura's fixed spacing scale. Screens compose these values; they do not invent local scales. */
object AuraSpacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
    val xxl = 48.dp
    /** Common non-scale values used across screens. */
    val hairline = 1.dp
    val tiny = 2.dp
    val small = 6.dp
    val medium = 10.dp
    val large = 14.dp
    val xl2 = 18.dp
    val xxl2 = 20.dp
}
